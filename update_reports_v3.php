EOD;

foreach ($folders as $folder) {
    $files = glob(__DIR__ . '/' . $folder . '/*.php');
    foreach ($files as $file) {
        $content = file_get_contents($file);
        
        $anchor = "sheetData.append(footerRow);";
        $pos = strpos($content, $anchor);
        
        if ($pos !== false) {
            
            // Extract title reliably
            preg_match("/const fileName = [`'\"]([^`-`'\"]+)/", $content, $matches);
            $report_title = isset($matches[1]) ? trim($matches[1]) : "Report";
            
            $new_pdf = str_replace('%%REPORT_TITLE%%', $report_title, $pdf_block);
            $new_print = str_replace('%%REPORT_TITLE%%', $report_title, $print_block);
            
            // Find the end of the excel block: "}\n}," after the anchor
            $excel_end = strpos($content, "},", $pos);
            if ($excel_end === false) continue;
            
            $cut_start = $excel_end + 2; // Right after "},"
            
            // Find the end of the buttons array. It's usually "] \n });"
            // Let's find the last occurrence of "});" in the file, and then backtrack to the "]"
            $dt_end = strrpos($content, "});");
            if ($dt_end === false) continue;
            
            // Backtrack to find the "]" of the buttons array
            $buttons_end = strrpos(substr($content, 0, $dt_end), "]");
            if ($buttons_end === false) continue;
            
            // Cut out everything between $cut_start and $buttons_end
            // And insert our two blocks separated by a comma
            $before = substr($content, 0, $cut_start);
            $after = substr($content, $buttons_end);
            
            $new_content = $before . "\n\n" . $new_pdf . ",\n\n" . $new_print . "\n\n            " . $after;
            
            file_put_contents($file, $new_content);
            echo "Perfectly Fixed: $file\n<br>";
            $modified++;
        }
    }
}
echo "Done. Perfectly fixed $modified files.";
?>
